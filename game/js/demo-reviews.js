// Они помечаются флагом demo: true, и на сайте показывается плашка «Демо-отзыв».
// Отзывы одной и той же игры всегда получаются одинаковыми, потому что
// случайные числа считаются от id игры.

// Простой генератор псевдослучайных чисел (mulberry32): одно и то же зерно -> одна и та же последовательность
function seededRandom(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

