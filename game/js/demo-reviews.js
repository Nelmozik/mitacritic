// Теги и подписи, которые уже есть в окне написания отзыва
const DEMO_TAGS = {
  exceptional: ['ЭТО ПОТРЯСЛО МЕНЯ', 'НЕ МОГУ ПЕРЕСТАТЬ ИГРАТЬ', 'ПРОВЕРЕННЫЙ ВРЕМЕНЕМ'],
  recommended: ['СТОИТ ПОПРОБОВАТЬ', 'ХОРОШО НА ВЕЧЕР'],
  meh: ['НА ЛЮБИТЕЛЯ'],
  skip: []
};

// Имена авторов. Специально обозначено, что это демо, чтобы их не приняли за реальных людей
const DEMO_AUTHORS = ['Демо-игрок А', 'Демо-игрок Б', 'Демо-игрок В', 'Демо-игрок Г', 'Демо-игрок Д'];

// Выбираем группу шаблонов по рейтингу игры
function demoTone(rating) {
  if (rating >= 8.5) return 'exceptional';
  if (rating >= 7) return 'recommended';
  if (rating >= 5.5) return 'meh';
  return 'skip';
}

// Создаём список демо-отзывов для одной игры
function makeDemoReviews(game) {
  const rand = seededRandom(game.id);
  const tone = demoTone(game.rating);
  const templates = DEMO_TEMPLATES[tone].slice();

  // перемешиваем шаблоны, чтобы у разных игр отзывы шли в разном порядке
  for (let i = templates.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [templates[i], templates[j]] = [templates[j], templates[i]];
  }

  // от 3 до 5 отзывов, но не больше, чем есть шаблонов
  const count = Math.min(templates.length, 3 + Math.floor(rand() * 3));
  const genre = (game.genres[0] || 'игры').toLowerCase();
  const year = game.year || 'неизвестном';
  const list = [];

  for (let i = 0; i < count; i++) {
    const tpl = templates[i];
    // подставляем данные игры в текст шаблона
    const fill = text => text.replace(/\{t\}/g, game.title).replace(/\{g\}/g, genre).replace(/\{y\}/g, year);

    // оценку берём около рейтинга игры, ±1 балл
    let score = Math.round(game.rating + (rand() * 2 - 1));
    score = Math.max(1, Math.min(10, score));

    list.push({
      id: game.id * 10 + i + 1000000000, // уникальный id, чтобы не пересекаться с настоящими отзывами
      demo: true,
      user: DEMO_AUTHORS[i],
      avatar: 'Д',
      score: score,
      title: fill(tpl.title),
      body: fill(tpl.body),
      tags: DEMO_TAGS[tone].slice(0, Math.floor(rand() * 2) + 1),
      rating: tone,
      pros: tpl.pros,
      cons: tpl.cons,
      likes: Math.floor(rand() * 40),
      dislikes: Math.floor(rand() * 6),
      date: '01.01.2026',
      helpful: false
    });
  }
  return list;
}

// Уже обработанные игры, чтобы не генерировать отзывы повторно
const demoDone = {};

// Возвращает все отзывы игры: настоящие (написанные пользователем) и демо.
// Для ещё не вышедших игр отзывов нет.
function getReviews(game) {
  if (!demoDone[game.id]) {
    demoDone[game.id] = true;
    if (game.status === 'released' && game.rating > 0) {
      REVIEWS[game.id] = (REVIEWS[game.id] || []).concat(makeDemoReviews(game));
    }
  }
  return REVIEWS[game.id] || [];
}
